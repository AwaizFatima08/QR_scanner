  'aztec' => 'Aztec code',
  'dataMatrix' => 'Data Matrix',
  'pdf417' => 'PDF417',
  'maxiCode' => 'MaxiCode',
  'ean13' => 'EAN-13 barcode',
  'ean8' => 'EAN-8 barcode',
  'upcA' => 'UPC-A barcode',
  'upcE' => 'UPC-E barcode',
  'code128' => 'Code 128 barcode',
  'code39' => 'Code 39 barcode',
  'code93' => 'Code 93 barcode',
  'codabar' => 'Codabar barcode',
  'itf' => 'ITF barcode',
  'dataBar' || 'dataBarExpanded' || 'dataBarLimited' => 'GS1 DataBar',
  _ => 'Code',
};
